class GeometryDiagnosticError(RuntimeError):
    pass


def _canonical_bytes(value: Any) -> bytes:
    try:
        return json.dumps(
            value,
            ensure_ascii=True,
            allow_nan=False,
            sort_keys=True,
            separators=(",", ":"),
        ).encode("ascii")
    except (TypeError, ValueError, UnicodeEncodeError) as error:
        raise GeometryDiagnosticError("value is not canonical JSON") from error


def _sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _file_record(path: Path) -> dict[str, Any]:
    try:
        path = path.expanduser().resolve(strict=True)
    except OSError as error:
        raise GeometryDiagnosticError(f"could not resolve file: {path}") from error
    if path.is_symlink() or not path.is_file():
        raise GeometryDiagnosticError(f"bound path must be one regular file: {path}")
    before = path.stat()
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(4 * 1024 * 1024), b""):
            digest.update(chunk)
    after = path.stat()
    if (before.st_dev, before.st_ino, before.st_size, before.st_mtime_ns) != (
        after.st_dev,
        after.st_ino,
        after.st_size,
        after.st_mtime_ns,
    ):
        raise GeometryDiagnosticError(f"file changed while hashing: {path}")
    return {
        "path": str(path),
        "size_bytes": int(after.st_size),
        "sha256": digest.hexdigest(),
    }


def _load_json(path: Path, *, label: str) -> tuple[dict[str, Any], dict[str, Any]]:
    record = _file_record(path)
    try:
        value = json.loads(Path(record["path"]).read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise GeometryDiagnosticError(f"could not parse {label}: {path}") from error
    if not isinstance(value, dict):
        raise GeometryDiagnosticError(f"{label} must be a JSON object")
    if _file_record(Path(record["path"])) != record:
        raise GeometryDiagnosticError(f"{label} changed while being read")
    return value, record


def _require_canonical_hash(value: Mapping[str, Any], *, label: str) -> str:
    declared = value.get("canonical_payload_sha256")
    if not isinstance(declared, str) or len(declared) != 64:
        raise GeometryDiagnosticError(f"{label} has no canonical payload hash")
    payload = dict(value)
    del payload["canonical_payload_sha256"]
    if _sha256_bytes(_canonical_bytes(payload)) != declared:
        raise GeometryDiagnosticError(f"{label} canonical payload hash drifted")
    return declared


def _validate_bound_file(value: Any, *, label: str) -> dict[str, Any]:
    if not isinstance(value, Mapping) or set(value) != {
        "path",
        "size_bytes",
        "sha256",
    }:
        raise GeometryDiagnosticError(f"{label} file record drifted")
    observed = _file_record(Path(str(value.get("path", ""))))
    if dict(value) != observed:
        raise GeometryDiagnosticError(f"{label} file identity drifted")
    return observed


def replay_selected_candidate(
    receipt_path: Path,
    *,
    expected_file_sha256: str = SELECTION_RECEIPT_SHA256,
) -> dict[str, Any]:
    """Fully replay the sealed three-candidate LR selection."""
    receipt, receipt_file = _load_json(receipt_path, label="LR selection receipt")
    if receipt_file["sha256"] != expected_file_sha256:
        raise GeometryDiagnosticError("LR selection receipt file hash drifted")
    canonical = _require_canonical_hash(receipt, label="LR selection receipt")
    if canonical != SELECTION_RECEIPT_CANONICAL_SHA256:
        raise GeometryDiagnosticError("LR selection canonical identity drifted")
    if (
        receipt.get("schema") != lr_selection.RECEIPT_SCHEMA
        or receipt.get("status") != "passed"
        or receipt.get("candidate_rank_lrs")
        != list(lr_selection.CANDIDATE_RANK_LRS)
        or receipt.get("optimizer_updates_per_candidate")
        != lr_selection.OPTIMIZER_UPDATES_PER_CANDIDATE
        or receipt.get("selection_partition") != lr_selection.SELECTION_PARTITION
        or receipt.get("selection_metric") != lr_selection.SELECTION_METRIC
        or receipt.get("secondary_selection_metric")
        != lr_selection.SECONDARY_SELECTION_METRIC
        or receipt.get("tie_break_rule") != list(lr_selection.TIE_BREAK_RULE)
    ):
        raise GeometryDiagnosticError("LR selection fixed contract drifted")
    invariants = receipt.get("invariants")
    if not isinstance(invariants, Mapping) or not invariants or any(
        value is not True for value in invariants.values()
    ):
        raise GeometryDiagnosticError("LR selection invariants are not all true")
    prereg = _validate_bound_file(
        receipt.get("preregistration"), label="LR preregistration"
    )
    try:
        _prereg_value, replayed_prereg = lr_selection._validate_preregistration(
            Path(prereg["path"])
        )
    except lr_selection.NewHeadLRSelectionError as error:
        raise GeometryDiagnosticError(str(error)) from error
    if replayed_prereg != prereg:
        raise GeometryDiagnosticError("LR preregistration binding drifted")

    raw_candidates = receipt.get("candidates")
    if not isinstance(raw_candidates, list) or len(raw_candidates) != len(
        lr_selection.CANDIDATE_RANK_LRS
    ):
        raise GeometryDiagnosticError("LR selection candidates drifted")
    by_lr = {}
    for row in raw_candidates:
        if not isinstance(row, Mapping) or type(row.get("rank_lr")) is not float:
            raise GeometryDiagnosticError("LR candidate record drifted")
        rank_lr = float(row["rank_lr"])
        if rank_lr in by_lr:
            raise GeometryDiagnosticError("LR selection contains a duplicate LR")
        by_lr[rank_lr] = row
    if set(by_lr) != set(lr_selection.CANDIDATE_RANK_LRS):
        raise GeometryDiagnosticError("LR candidate set drifted")

    candidates = []
    for rank_lr in lr_selection.CANDIDATE_RANK_LRS:
        row = by_lr[rank_lr]
        summary_file = _validate_bound_file(
            row.get("summary_file"), label=f"LR={rank_lr} summary"
        )
        try:
            replayed = lr_selection._validate_summary(
                Path(summary_file["path"]), rank_lr=rank_lr
            )
        except lr_selection.NewHeadLRSelectionError as error:
            raise GeometryDiagnosticError(str(error)) from error
        expected_row = {
            "rank_lr": replayed.rank_lr,
            "summary_file": replayed.summary_file,
            "checkpoint_file": replayed.checkpoint_file,
            "config_file": replayed.config_file,
            "metrics": replayed.metrics,
        }
        if dict(row) != expected_row:
            raise GeometryDiagnosticError(f"LR={rank_lr} candidate binding drifted")
        candidates.append(replayed)
    try:
        shared_hashes = lr_selection._require_shared_contracts(candidates)
        selected = lr_selection._select_candidate(candidates)
    except lr_selection.NewHeadLRSelectionError as error:
        raise GeometryDiagnosticError(str(error)) from error
    if receipt.get("shared_contract_sha256") != shared_hashes:
        raise GeometryDiagnosticError("LR shared contract hashes drifted")
    if receipt.get("selected_rank_lr") != selected.rank_lr:
        raise GeometryDiagnosticError("LR selection tie-break replay drifted")
    return {
        "receipt_file": receipt_file,
        "canonical_payload_sha256": canonical,
        "selected_rank_lr": selected.rank_lr,
        "checkpoint_file": selected.checkpoint_file,
        "config_file": selected.config_file,
        "summary_file": selected.summary_file,
        "selection_metrics": selected.metrics,
        "preregistration_file": prereg,
        "shared_contract_sha256": shared_hashes,
    }


